# Variables
# ----------
# A variable stores data so we can use it later in a program.
# Think of it as a labeled box that holds a value.
# Python detects the data type automatically -- no declaration needed.

# Basic example
name = "Chichi"
age = 16
height = 5.8

print(name)
print(age)
print(height)

# Variables can be reassigned (the label now points to a new value)
age = 30
print(age)

# Naming rules:
# - Use lowercase letters, numbers, and underscores
# - Must start with a letter or underscore
# - Be descriptive: first_name reads better than fn

first_name = "Nitik"
print(first_name)
